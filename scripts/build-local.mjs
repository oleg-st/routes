import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dataNames} from '../data/runtime-loader.js';

const root=fileURLToPath(new URL('../',import.meta.url));
const output=new URL('../local.html',import.meta.url);
const data=Object.fromEntries(await Promise.all(dataNames.map(async name=>[
  name,JSON.parse(await readFile(new URL(`../data/${name}.json`,import.meta.url),'utf8')),
])));
// Replace only the HTTP loader. The same application and map modules run in both modes.
const result=await build({
  absWorkingDir:root,
  entryPoints:['app.js'],
  bundle:true,
  format:'iife',
  target:['es2022'],
  minify:true,
  write:false,
  banner:{js:'// Generated by npm run build:local. Do not edit directly.'},
  plugins:[{
    name:'embedded-local-data',
    setup(builder){
      builder.onLoad({filter:/[/\\]runtime-loader\.js$/},()=>({
        contents:`export async function loadData(){return ${JSON.stringify(data)};}`,
        loader:'js',
      }));
    },
  }],
});
const template=await readFile(new URL('../index.html',import.meta.url),'utf8');
const entry='<script type="module" src="app.js"></script>';
if(!template.includes(entry))throw new Error('Cannot find the application entry in index.html.');
const script=result.outputFiles[0].text.replace(/<\/script/gi,'<\\/script');
const source=template.replace('href="index.html"','href="local.html"').replace(entry,()=>`<script>\n${script}\n</script>`);
if(process.argv.includes('--check')){
  const existing=await readFile(output,'utf8').catch(()=>null);
  if(existing!==source)throw new Error('Local build is missing or outdated. Run npm run build:local.');
  console.log('Local build is up to date.');
}else{
  await writeFile(output,source);
  console.log(`Built local.html (${Math.round(Buffer.byteLength(source)/1024)} KB). Open it directly in your browser.`);
}
