// Regath blood comes from OnDeath abilities, independently of kill score.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {loadGameCatalogSource,gamePlannerRoot,readJson,sha,characterIdToEnemyId} from './game-catalog-source.mjs';
import {selectMapFrame} from './game-source-identity.mjs';

const s=loadGameCatalogSource(),dungeonId='Level.ID.MoorCastle';
const constants=new Map(),sourceHashes={};
for(const r of s.manifest.results.filter(r=>r.Kind==='raw'&&/\/RawDataTables\/AbilityConstants\//i.test(r.Source))){
  const bytes=fs.readFileSync(gamePlannerRoot+'/'+r.Output);
  for(const line of bytes.toString('utf8').split(/\r?\n/)){
    const [key,value,...rest]=line.split(';')[0].trim().split(',').map(v=>v.trim());
    if(!/\.SpawnBlood\.(BloodAmount|BlobsToSpawn)$/.test(key)&&key!=='MC_BloodFountain.BloodCapacity')continue;
    assert.equal(sha(bytes),r.Sha256,'Stale blood constants: '+r.Source);
    assert.equal(rest.length,0,'Review time-dependent blood constant: '+key);
    assert.ok(Number.isFinite(Number(value)),'Invalid blood constant: '+key);
    if(constants.has(key))assert.equal(constants.get(key),Number(value),'Conflicting blood constant: '+key);
    constants.set(key,Number(value));sourceHashes[r.Source]=r.Sha256;
  }
}
function scalar(value){
  const row=value?.Curve?.RowName;
  const factor=!row||row==='None'?1:constants.get(row);
  assert.ok(Number.isFinite(value?.Value)&&Number.isFinite(factor),'Missing blood constant: '+row);
  return value.Value*factor;
}
const drops={};
const dungeon=readJson('data/dungeons.json').find(d=>d.id===dungeonId);
const enemyIds=new Set(dungeon.enemies.map(p=>p.id));
// Regath also uses SandTomb NPCs. Select actual dungeon members and follow
// the inherited blood-drop ability instead of relying on asset-name prefixes.
function isBloodDrop(ref){
  const seen=new Set();
  for(let o=s.object(s.object(ref)?.ClassDefaultObject);o;o=s.object(o.Template)){
    assert.ok(!seen.has(o.ref),'Blood ability template cycle');seen.add(o.ref);
    if(o.Name==='Default__GA_MC_BloodFountain_SpawnBlood_C')return true;
  }
  return false;
}
for(const npc of s.npcs.filter(n=>n.characterId&&enemyIds.has(characterIdToEnemyId(n.characterId)))){
  const behavior=s.object(npc.properties.BehaviorComponentClass);
  const abilities=s.properties(behavior?.ClassDefaultObject).Phases?.flatMap(p=>p.Value.Abilities??[])??[];
  const death=abilities.filter(a=>a.EnabledByDefault&&a.ActivationType?.endsWith('::OnDeath')&&isBloodDrop(a.AbilityClass));
  if(!death.length)continue;
  assert.equal(death.length,1,'Multiple blood drops: '+npc.characterId);
  const ability=s.object(death[0].AbilityClass),p=s.properties(ability.ClassDefaultObject);
  const orbs=scalar(p.NumBuffsToDrop),bloodPerOrb=scalar(p.BloodAmount);
  assert.ok(Number.isInteger(orbs)&&orbs>0&&Number.isInteger(bloodPerOrb)&&bloodPerOrb>0);
  drops[characterIdToEnemyId(npc.characterId)]={orbs,bloodPerOrb,blood:orbs*bloodPerOrb,source:ability.ref};
}
assert.equal(Object.keys(drops).length,7,'Review Regath blood-dropping enemies');
const fountain=[...s.objects.values()].find(o=>o.Name==='Default__BP_MC_BloodFountain_C');
const bloodPerTower=scalar(s.properties(fountain.ref).BloodCapacity);
assert.equal(bloodPerTower,20,'Review Regath tower capacity');
const rawPath=(process.env.GAME_DATA_ROOT??'private/game-data/all-dungeons')+'/MoorCastle/raw/MoorCastle.json';
const rawBytes=fs.readFileSync(rawPath),raw=JSON.parse(rawBytes);
assert.equal(readJson(rawPath.replace('/raw/MoorCastle.json','/extracted.json')).steamBuild,s.manifest.steamBuild);
sourceHashes[rawPath]=sha(rawBytes);
const frames=readJson('data/game-map-frames.json')[dungeonId];
// BloodFountain is the charging location. BloodPillar actors are the separate
// decorative pillars at the central door, not the three collection towers.
const towers=raw.Objects.filter(({Object:o})=>o.Type==='SceneComponent'&&o.Name==='DefaultSceneRoot'&&o.Outer?.ObjectName.startsWith("BP_MC_BloodFountain_C'")).map(({Object:o})=>{
  assert.ok(!o.Properties.AttachParent,'Attached tower requires transform composition');
  const p=o.Properties.RelativeLocation,worldPosition={x:p.X,y:p.Y,z:p.Z};
  const name=o.Outer.ObjectName.split('.').at(-1).replace("'",'');
  return {id:name,worldPosition,...selectMapFrame(worldPosition,frames),source:o.Outer.ObjectPath};
}).sort((a,b)=>a.id.localeCompare(b.id));
assert.equal(towers.length,3,'Review Regath tower placements');
assert.equal(new Set(towers.map(t=>t.id)).size,3);
const rules={steamBuild:s.manifest.steamBuild,dungeonId,bloodPerTower,drops,towers,sourceHashes};
const output=process.env.GAME_BLOOD_OUTPUT??'data';fs.mkdirSync(output,{recursive:true});
fs.writeFileSync(output+'/game-blood.js','// Generated by scripts/prepare-blood-data.mjs from installed-game data.\nexport const bloodRules='+JSON.stringify(rules,null,2)+';\n');
console.log('Regath blood: 3 towers, 20 blood each; '+Object.keys(drops).length+' enemy types.');
