import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {usedImages} from './image-assets.mjs';
import {avifPath, originalFor, compressImages, hashFile, combinedRasterSize, prunePublicImages, resizeImageMetadata} from './avif-assets.mjs';
import {fullMaps} from '../data/full-maps.js';
import {combinedLayouts, combinedBuildId} from '../data/combined-layouts.js';

const nonMapsOnly = process.argv.includes('--non-maps');
const required = [...new Set(usedImages({includeLayers:true}).map(avifPath))];
const files = required.filter(file => !nonMapsOnly || !/^(?:private\/)?images\/dungeons\//.test(file));
const dungeons = JSON.parse(fs.readFileSync('data/dungeons.json', 'utf8'));
const jobs = files.map(destination => {
  const layout = Object.values(combinedLayouts).find(map => avifPath(map.path) === destination);
  const dungeon = layout && dungeons.find(d => combinedLayouts[d.id] === layout);
  return {source: originalFor(destination), destination, ...(layout ? {rasterSize: combinedRasterSize(layout, dungeon)} : {})};
});
for (const dungeon of dungeons) for (const map of dungeon.mapImages) {
  const original = originalFor(map.path);
  if (hashFile(original) !== (map.sourceSha256 || map.sha256)) throw new Error(`Original differs from dataset: ${original}`);
}
await compressImages(jobs);
const outputs = new Map(files.map(file => [file, hashFile(file)]));
function updateImage(image) {
  const destination = avifPath(image.path);
  if (!outputs.has(destination)) return;
  if (!image.path.endsWith('.avif')) {
    image.sourcePath = image.path;
    if (image.sha256) image.sourceSha256 = image.sha256;
  }
  image.path = destination;
  image.sha256 = outputs.get(destination);
  resizeImageMetadata(image, jobs.find(job => job.destination === destination)?.maxSize);
}
function visit(value) {
  if (!value || typeof value !== 'object') return;
  if (typeof value.path === 'string' && /^(?:private\/)?images\//.test(value.path)) updateImage(value);
  for (const child of Object.values(value)) visit(child);
}
for (const name of nonMapsOnly ? ['enemies', 'heroes'] : ['dungeons', 'enemies', 'abilities', 'heroes']) {
  const filename = `data/${name}.json`;
  const value = JSON.parse(fs.readFileSync(filename, 'utf8'));
  visit(value);
  fs.writeFileSync(filename, JSON.stringify(value, null, 2) + '\n');
}
// Map coordinates and rasters remain untouched during a non-map rebuild.
if (!nonMapsOnly) {
  for (const map of Object.values(combinedLayouts)) {
    updateImage(map);
    const job = jobs.find(job => job.destination === map.path);
    map.pixelWidth = job.rasterSize.width;
    map.pixelHeight = job.rasterSize.height;
    for (const source of Object.values(map.sources)) updateImage(source);
    for (const source of Object.values(map.artworkSources || {})) updateImage(source);
    if (map.referenceId) map.referenceSha256 = createHash('sha256').update(JSON.stringify(fullMaps[map.referenceId])).digest('hex');
  }
  fs.writeFileSync('data/combined-layouts.js', `// Generated by scripts/prepare-combined-maps.mjs.\nexport const combinedBuildId=${JSON.stringify(combinedBuildId)};\nexport const combinedLayouts=${JSON.stringify(combinedLayouts, null, 2)};\n`);
}
const bytes = files.reduce((total, file) => total + fs.statSync(file).size, 0);
if (!nonMapsOnly) prunePublicImages(required);
console.log(`${files.length} required AVIF images: ${(bytes / 1024 ** 2).toFixed(2)} MiB. Originals remain private.`);
