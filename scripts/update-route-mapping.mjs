import fs from 'node:fs';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import {customDungeons} from '../data/custom-dungeons.js';
import {modifierPlacementIds} from '../data/modifier-spawns.js';

// Indexes remain stable within a build. Routes from other builds are rejected
// before decoding, so a new game build starts a fresh, smaller dictionary.
const filename='data/route-mapping.js';
const buildId=JSON.parse(fs.readFileSync('data/manifest.json')).buildId;
const previous=fs.existsSync(filename)?(await import(pathToFileURL(path.resolve(filename)))).routeMapping:null;
const mapping=previous?.buildId===buildId?structuredClone(previous):{version:1,buildId,dungeons:{}};
const initial=structuredClone(mapping);
const raw=JSON.parse(fs.readFileSync('data/dungeons.json'));
const signature=members=>[...members].sort((a,b)=>a-b).join(',');
for(const d of raw){
 if(d.routeBuildId!==buildId)throw Error('Mixed route build: '+d.id);
 const entry=mapping.dungeons[d.id]??={placements:[],packs:[]};
 for(const id of [...new Set([...d.enemies.map(p=>p.placementId),...(customDungeons[d.id]?.packs??[]).flatMap(p=>p.members),...modifierPlacementIds(d.id)])].sort())if(!entry.placements.includes(id))entry.placements.push(id);
 function register(id,ids){
  const members=ids.map(id=>entry.placements.indexOf(id));
  if(members.some(i=>i<0))throw Error('Unknown placement in '+id);
  let index=entry.packs.findIndex(p=>p.id===id&&signature(p.members)===signature(members));
  if(index<0){index=entry.packs.length;entry.packs.push({id,members});}
  return index;
 }
 for(const id of [...new Set(d.enemies.map(p=>p.packId).filter(Boolean))].sort())register(id,d.enemies.filter(p=>p.packId===id).map(p=>p.placementId));
 for(const p of customDungeons[d.id]?.packs??[])register(p.id,p.members);
}
for(const [id,before]of Object.entries(initial.dungeons))for(const key of ['placements','packs']){
 if(JSON.stringify(mapping.dungeons[id][key].slice(0,before[key].length))!==JSON.stringify(before[key]))throw Error('Existing mapping was changed: '+id+' '+key);
}
const text='// Route dictionaries for this game build. Generated by scripts/update-route-mapping.mjs.\nexport const routeMapping='+JSON.stringify(mapping)+';\n';
if(process.argv.includes('--check')){if(fs.readFileSync(filename,'utf8')!==text)throw Error('Route mapping needs appended entries. Run node scripts/update-route-mapping.mjs.');}
else fs.writeFileSync(filename,text);
console.log('Route mapping:',Object.keys(mapping.dungeons).length,'dungeons,',Object.values(mapping.dungeons).reduce((n,d)=>n+d.packs.length,0),'immutable pack entries');
