export function placementHealth(pos,enemy,route,{difficulty=route.difficulty}={}){
  if(difficulty===undefined)return null;
  if(!pos)return null;
  if(nonCombatBossIds.has(pos.id))return 0;
  const stats=enemy??modifierStats[pos.modifier];
  if(stats?.baseHealth==null&&stats?.dungeonScore===0)return 0;
  if(!stats?.isBoss&&route.excluded.includes(pos.placementId)){
    const chicken=polymorphChicken(stats);if(!chicken)return null;
    // A fresh NPC uses its own HP and affix eligibility, without the original's
    // Empowered selection. Integer base HP before scaling matches logged chickens.
    return Math.trunc(enemyHealth({...chicken,baseHealth:Math.ceil(chicken.baseHealth)},{difficulty,...difficultyHealthModifiers(route,chicken.id,{difficulty})}));
  }
  return enemyHealth(stats,{difficulty,...difficultyHealthModifiers(route,pos.id,{difficulty,isBossMinion:pos.isBossMinion||stats?.isBossMinion}),empowered:!pos.modifier&&!stats?.isBoss&&route.modifiers?.empowered?.active&&route.modifiers.empowered.enemies.includes(pos.placementId)});
}
export function positionsHealth(members,enemies,route){
  if(route.difficulty===undefined)return null;
  let health=0;const seen=new Set();
  for(const pos of members){
    if(!pos)return null;
    // Separate map markers for one multi-phase actor represent one health pool.
    const key=pos.gameGuid??pos.placementId;if(seen.has(key))continue;seen.add(key);
    const value=placementHealth(pos,enemies.get(pos.id),route);if(value==null)return null;health+=value;
  }
  return health;
}
export const shadowHealth=route=>route.difficulty===undefined?null:enemyHealth({baseHealth:shadowBaseHealth},{difficulty:route.difficulty});
export function routeHealth(route,dungeon,enemies){
  if(route.difficulty===undefined)return {pulls:route.pulls.map(()=>({mobs:null,shadow:null,total:null})),mobs:null,shadow:null,total:null,dps:null};
  const positions=new Map(effectivePositions(route,dungeon).map(p=>[p.placementId,p]));
  const inactive=new Set([...replacedIds(route,dungeon),...['ghorn','witch'].filter(k=>!route.modifiers?.[k]?.active).map(modifierId)]);
  const timeline=route.shadow?shadowTimeline(route,dungeon,enemies):[];
  const members=ids=>[...new Set(ids)].filter(id=>!inactive.has(id)).map(id=>positions.get(id));
  const pulls=route.pulls.map((pull,i)=>{
    const mobs=positionsHealth(members(pull.enemies),enemies,route),shadow=(timeline[i]?.spawns??0)*shadowHealth(route);
    return {mobs,shadow,total:mobs==null?null:mobs+shadow};
  });
  const mobs=positionsHealth(members(route.pulls.flatMap(p=>p.enemies)),enemies,route),shadow=pulls.reduce((sum,p)=>sum+p.shadow,0);
  const total=mobs==null?null:mobs+shadow;
  return {pulls,mobs,shadow,total,dps:total!=null&&dungeon.timerSeconds>0?total/dungeon.timerSeconds:null};
}
export function assignEnemies(route,pullId,ids,{toggle=true}={}){
  const pull=route.pulls.find(p=>p.id===pullId);if(!pull)return;
  const chosen=new Set(ids), remove=toggle&&ids.length>0&&ids.every(id=>pull.enemies.includes(id));
  for(const p of route.pulls)p.enemies=p.enemies.filter(id=>!chosen.has(id));
  if(!remove)pull.enemies.push(...chosen);
}
export function validateRoute(value,dungeons,enemies){
  if(!value||![1,2,3].includes(value.version))throw new Error('Unsupported format. Use a route JSON file from this planner (version 1, 2 or 3).');
  const dungeon=dungeons.find(d=>d.id===value.dungeonId);
  if(!dungeon)throw new Error('This dungeon is not available in the current dataset.');
  assertRouteBuild(value,dungeon);
  if(value.difficulty!==undefined)checkDifficulty(dungeon.id,value.difficulty);
  if(!Array.isArray(value.pulls)||value.pulls.length>(value.version===3?10000:500))throw new Error('Invalid pull list.');
  const canonical=id=>id;
  const original=new Set(dungeon.enemies.map(e=>e.placementId)),known=new Set([...original,...modifierPlacementIds(dungeon.id)]),seen=new Set(),rawSeen=new Set(),pullIds=new Set();
  const modifiers=defaultModifiers();
  if(value.modifiers!==undefined){
    if(!value.modifiers||typeof value.modifiers!=='object')throw new Error('Invalid modifiers.');
    const emp=value.modifiers.empowered;
    if(emp){if(!Array.isArray(emp.enemies)||!emp.enemies.every(id=>original.has(id)))throw new Error('Invalid empowered enemies.');modifiers.empowered={active:emp.active===true,enemies:[...new Set(emp.enemies)]};}
    for(const k of ['ghorn','witch']){
      const m=value.modifiers[k];if(!m)continue;
      if(m.packId!==null&&typeof m.packId!=='string')throw new Error('Invalid replacement pack.');
      if(m.active&&!m.packId)throw new Error('Choose a replacement pack.');
      if(!m.packId&&m.replacedEnemies!==undefined)throw new Error('A replacement needs a pack.');
      if(m.packId&&!dungeon.enemies.some(p=>p.packId===m.packId))throw new Error('Invalid replacement pack.');
      if(m.replacedEnemies!==undefined&&!Array.isArray(m.replacedEnemies))throw new Error('Invalid replacement enemies.');
      const members=m.packId?replacementMembers(dungeon,m.packId,m.replacedEnemies):[];
      if(m.packId&&(!members.length||!members.every(id=>original.has(canonical(id)))))throw new Error('Invalid replacement pack.');
      if(m.replacedEnemies!==undefined&&(!Array.isArray(m.replacedEnemies)||!m.replacedEnemies.length))throw new Error('Invalid replacement enemies.');
      if(enemies&&dungeon.enemies.some(p=>members.includes(p.placementId)&&enemies.get(p.id)?.isBoss))throw new Error('Cannot replace a boss pack.');
      modifiers[k]={active:m.active===true,packId:m.packId,...(m.packId?{replacedEnemies:[...new Set(members.map(canonical))]}:{})};
    }
    if(modifiers.ghorn.replacedEnemies?.some(id=>modifiers.witch.replacedEnemies?.includes(id)))throw new Error('Replacement enemies must be different.');
  }
  for(const k of ['ghorn','witch'])if(!modifiers[k].packId)for(const id of modifierPlacementIds(dungeon.id,k))known.delete(id);
  const text=(v,max=200)=>{if(value.version===3&&typeof v==='string'&&v.length>max)throw new Error('Route text is too long.');return typeof v==='string'?v.slice(0,max):'';};
  const pulls=value.pulls.map((p,i)=>{
    if(!p||!Array.isArray(p.enemies))throw new Error('Invalid pull.');
    const ids=[];
    for(const rawId of p.enemies){
      if(rawSeen.has(rawId))throw new Error('An enemy is assigned to multiple pulls. Import cancelled.');
      rawSeen.add(rawId);const id=canonical(rawId);
      if(!known.has(id))throw new Error('The route contains enemy placements from another dataset. Import cancelled.');
      if(seen.has(id))continue;
      seen.add(id);ids.push(id);
    }
    const id=text(p.id)||uid();if(pullIds.has(id))throw new Error('Duplicate pull ID.');pullIds.add(id);
    const name=englishDefaultLabel(text(p.name))||`Pull ${i+1}`;
    return {id,name,customName:hasCustomPullName({...p,name}),color:/^#[0-9a-f]{6}$/i.test(p.color)?p.color:COLORS[i%COLORS.length],enemies:ids,note:text(p.note,value.version===3?1_000_000:4000)};
  });
  if(value.drawings!==undefined&&!Array.isArray(value.drawings))throw new Error('Invalid drawings.');
  if(value.version===3&&value.drawings?.length>10000)throw new Error('Too many drawings.');
  const drawingIds=new Set();
  const drawings=(value.drawings||[]).slice(0,value.version===3?10000:500).map(d=>{
    if(!d||!Array.isArray(d.points)||d.points.length<1||d.points.length>5000)throw new Error('Invalid drawing.');
    if(!d.points.every(p=>Array.isArray(p)&&p.length===2&&p.every(n=>Number.isFinite(n)&&Math.abs(n)<100000)))throw new Error('Invalid drawing coordinates.');
    if(!drawingMap(dungeon,d.mapId)||!d.points.every(p=>p.every(n=>Number.isFinite(n)&&Math.abs(n)<100000)))throw new Error('Invalid drawing.');
    if(['portal','invis'].includes(d.kind)&&d.points.length!==2)throw new Error('Portal and invisibility paths need two endpoints.');
    const kind=['line','portal','invis','note'].includes(d.kind)?d.kind:'line';
    if(kind==='line'&&d.points.length<2)throw new Error('Arrows need two endpoints.');
    const points=kind==='line'&&value.version!==3?[d.points[0],d.points.at(-1)]:d.points;
    // Keep annotation identity across local reloads; legacy drawings acquire an ID once.
    const id=text(d.id)||uid();if(drawingIds.has(id))throw new Error('Duplicate drawing ID.');drawingIds.add(id);
    return {id,mapId:d.mapId,kind,color:/^#[0-9a-f]{6}$/i.test(d.color)?d.color:COLORS[0],...(kind==='line'&&d.width!==undefined?{width:[2,3,5].includes(d.width)?d.width:3}:{}),...(kind==='note'&&d.icon!==undefined?{icon:text(d.icon,50)||'number'}:{}),text:text(d.text,value.version===3?1_000_000:500),points:points.map(p=>[...p])};
  });
  const markerIds=new Set();
  if(value.markers!==undefined&&(!Array.isArray(value.markers)||value.markers.length>(value.version===3?10000:500)))throw new Error('Invalid markers.');
  const markers=(value.markers||[]).map(m=>{
    if(!m||!Array.isArray(m.position)||m.position.length!==2||!m.position.every(n=>Number.isFinite(n)&&Math.abs(n)<100000))throw new Error('Invalid marker position.');
    const projected={mapId:m.mapId,points:[m.position]};
    if(!drawingMap(dungeon,projected.mapId))throw new Error('Invalid marker map.');
    const id=text(m.id)||uid();if(markerIds.has(id))throw new Error('Duplicate marker ID.');markerIds.add(id);
    return {id,mapId:projected.mapId,position:projected.points[0],color:/^#[0-9a-f]{6}$/i.test(m.color)?m.color:COLORS[0],icon:text(m.icon,50)||'pin',label:text(m.label,value.version===3?1_000_000:4000)};
  });
  if(value.excluded!==undefined&&(!Array.isArray(value.excluded)||!value.excluded.every(id=>known.has(canonical(id)))))throw new Error('Invalid excluded enemies.');
  if(value.priorityTargets!==undefined&&(!Array.isArray(value.priorityTargets)||!value.priorityTargets.every(id=>known.has(canonical(id)))))throw new Error('Invalid priority targets.');
  const bossIds=new Set(dungeon.enemies.filter(p=>enemies?.get(p.id)?.isBoss).map(p=>p.placementId));
  for(const kind of ['ghorn','witch'])if(enemies?.get(modifierId(kind))?.isBoss)for(const id of modifierPlacementIds(dungeon.id,kind))bossIds.add(id);
  return restrictRouteModifiers({version:2,id:text(value.id)||uid(),buildId:text(value.buildId),dungeonId:dungeon.id,...(value.difficulty===undefined?{}:{difficulty:value.difficulty}),name:englishDefaultLabel(text(value.name))||'Imported route',shadow:value.shadow===true,modifiers,pulls,drawings,...(markers.length?{markers}:{}),excluded:[...new Set((value.excluded||[]).map(canonical))].filter(id=>!bossIds.has(id)),priorityTargets:[...new Set((value.priorityTargets||[]).map(canonical))]});
}


// R1: base64url(raw DEFLATE(UTF-8 JSON tuples)). IDs used only by the UI are
// regenerated on import. Sorted dataset indexes replace long placement/pack IDs;
// a dataset fingerprint identifies legacy R1/R2 dictionaries. R3 uses permanent
// append-only pack compositions and placement indexes across grouping changes.
// R4 stores differences between successive member tokens in each list.
const PREFIX='R1.',LIMIT=3_000_000;
const tooLarge=()=>new Error('Route is too large (maximum 3 MB).');
const invalid=()=>new Error('Invalid compact route.');
const trim=row=>{while(row.at(-1)===null)row.pop();return row;};
const optionalList=list=>list?.length?list:null;
const colorCode=color=>COLORS.includes(color)?COLORS.indexOf(color):color;
// Export at 0.01 map-pixel precision without changing the editable route.
// Keep valid coordinates just inside the import limit from rounding outside it.
const compactPoint=point=>point.map(n=>{const rounded=Math.round(n*100)/100;return Math.abs(rounded)<100000?rounded:n;});
function readColor(value,fallback){
  if(value==null)return fallback;
  if(Number.isInteger(value)&&COLORS[value])return COLORS[value];
  if(typeof value==='string'&&/^#[0-9a-f]{6}$/i.test(value))return value;
  throw invalid();
}
function base64url(bytes){
  let binary='';
  for(let i=0;i<bytes.length;i+=8192)binary+=String.fromCharCode(...bytes.subarray(i,i+8192));
  return btoa(binary).replace(/\+/g,'-').replace(/\//g,'_').replace(/=+$/,'');
}
async function transform(bytes,Stream){
  const reader=new Blob([bytes]).stream().pipeThrough(new Stream('deflate-raw')).getReader();
  const chunks=[];let size=0;
  try{
    for(;;){
      const {done,value}=await reader.read();if(done)break;
      size+=value.length;if(size>LIMIT){await reader.cancel();throw tooLarge();}
      chunks.push(value);
    }
  }finally{reader.releaseLock();}
  const output=new Uint8Array(size);let offset=0;
  for(const chunk of chunks){output.set(chunk,offset);offset+=chunk.length;}
  return output;
}
async function dictionary(dungeon){
  const placements=[...new Set([...dungeon.enemies.map(e=>e.placementId),...modifierPlacementIds(dungeon.id)])].sort();
  const packs=[...new Set(dungeon.enemies.map(e=>e.packId).filter(Boolean))].sort();
  const bytes=new TextEncoder().encode(JSON.stringify([placements,packs]));
  const digest=new Uint8Array(await crypto.subtle.digest('SHA-256',bytes));
  return {placements,packs,fingerprint:base64url(digest.subarray(0,12))};
}
function indexOf(list,id){const index=list.indexOf(id);if(index<0)throw invalid();return index;}
function itemAt(list,index){if(!Number.isInteger(index)||index<0||index>=list.length)throw invalid();return list[index];}
function tuple(value,max){if(!Array.isArray(value)||value.length>max)throw invalid();return value;}
function list(value){if(value==null)return [];if(!Array.isArray(value))throw invalid();return value;}
function flag(value){if(value!=null&&value!==1)throw invalid();return value===1;}
function memberDeltas(values,decode=false){
  let previous=0;
  return list(values).map(value=>{
    if(!Number.isSafeInteger(value))throw invalid();
    const result=decode?previous+value:value-previous;
    if(!Number.isSafeInteger(result))throw invalid();
    previous=decode?result:value;
    return result;
  });
}

export async function encodeRoute(route,dungeon){
  assertRouteBuild(route,dungeon);
  route=structuredClone(route);
  const extended=Boolean(route.priorityTargets?.length||route.difficulty!==undefined||route.markers?.length||route.pulls.length>500||route.drawings.length>500||route.pulls.some(p=>p.note?.length>4000)||route.drawings.some(d=>d.icon||d.kind==='line'&&d.points.length>2||d.text?.length>500));
  if(extended)validateRoute({...route,version:3},[dungeon]); // Reject oversized content; never silently truncate a CRDT view.
  const permanent=routeDictionary(dungeon.id);
  const {placements,packs,fingerprint}=await dictionary(dungeon);
  const ids=values=>permanent?encodeMembers(permanent,values):values.map(id=>indexOf(placements,id));
  const pulls=route.pulls.map((p,i)=>trim([
    ids(p.enemies),p.name===`Pull ${i+1}`?null:p.name,
    p.color===pullColor(i)?null:colorCode(p.color),p.note||null,p.customName?1:null,
  ]));
  const drawings=route.drawings.map(d=>trim([
    d.mapId,['line','portal','invis','note'].indexOf(d.kind),d.points.map(compactPoint),
    d.color===COLORS[0]?null:colorCode(d.color),d.text||null,d.width??null,d.kind==='note'?(d.icon??null):null,
  ]));
  const modifiers=['empowered','ghorn','witch'].map(kind=>{
    const m=route.modifiers?.[kind];if(!m)return null;
    let packIndex=m.packId==null?null:permanent?permanent.packs.findIndex(p=>p.id===m.packId):indexOf(packs,m.packId);
    if(permanent&&m.packId&&m.replacedEnemies){
      const expected=[...m.replacedEnemies].sort().join('|');
      const exact=permanent.packs.findIndex(p=>p.id===m.packId&&p.members.map(i=>permanent.placements[i]).sort().join('|')===expected);
      if(exact>=0)packIndex=exact;
    }
    if(packIndex===-1)throw new Error('Replacement pack is not registered.');
    // R3 already restores these members from the permanent pack composition.
    // Omit only exact matches, including order; custom subsets stay explicit.
    const inherited=packIndex==null?null:permanent?.packs[packIndex]?.members;
    const redundant=inherited&&m.replacedEnemies?.length===inherited.length&&inherited.every((index,i)=>permanent.placements[index]===m.replacedEnemies[i]);
    const row=kind==='empowered'?[m.active?1:null,optionalList(ids(m.enemies))]:[
      m.active?1:null,packIndex,
      m.replacedEnemies===undefined||redundant?null:ids(m.replacedEnemies),
    ];
    return trim(row).length?row:null;
  });
  const payload=trim([
    route.dungeonId.replace(/^Level\.ID\./,''),route.buildId,permanent?'m1':fingerprint,route.name,pulls,
    optionalList(drawings),optionalList(ids(route.excluded)),optionalList(trim(modifiers)),route.shadow?1:null,
  ]);
  if(extended){while(payload.length<9)payload.push(null);payload.push((route.markers||[]).map(m=>[m.mapId,compactPoint(m.position),colorCode(m.color),m.icon,m.label]));}
  if(route.difficulty!==undefined)payload.push(route.difficulty);
  // Optional slot 11 keeps target annotations separate from scoring and affixes.
  if(route.priorityTargets?.length){while(payload.length<11)payload.push(null);payload.push(ids(route.priorityTargets));}
  const bytes=new TextEncoder().encode(JSON.stringify(payload));
  if(bytes.length>LIMIT)throw tooLarge();
  let prefix=permanent?'R3.':extended?'R2.':PREFIX;
  let compressed=await transform(bytes,CompressionStream);
  if(permanent){
    // Keep R3 when deltas do not help (e.g. already compact whole-pack lists).
    for(const pull of payload[4])pull[0]=memberDeltas(pull[0]);
    if(payload[6]!=null)payload[6]=memberDeltas(payload[6]);
    if(payload[11]!=null)payload[11]=memberDeltas(payload[11]);
    for(const [i,modifier] of (payload[7]??[]).entries()){
      const slot=i===0?1:2;
      if(modifier?.[slot]!=null)modifier[slot]=memberDeltas(modifier[slot]);
    }
    const deltaBytes=new TextEncoder().encode(JSON.stringify(payload));
    if(deltaBytes.length<=LIMIT){
      const candidate=await transform(deltaBytes,CompressionStream);
      if(candidate.length<compressed.length){compressed=candidate;prefix='R4.';}
    }
  }
  return prefix+base64url(compressed);
}

async function expandRoute(payload,dungeons,extended=false,mapped=false,deltas=false){
  const [id,buildId,fingerprint,name,pulls,drawings,excluded,mods,shadow,markers,difficulty,priorityTargets]=tuple(payload,extended?12:9);
  const dungeon=dungeons.find(d=>d.id===`Level.ID.${id}`);
  if(!dungeon)throw new Error('This dungeon is not available in the current dataset.');
  assertRouteBuild({buildId},dungeon);
  let {placements,packs,fingerprint:expected}=await dictionary(dungeon);
  const permanent=routeDictionary(dungeon.id);
  if(mapped){if(fingerprint!=='m1'||!permanent)throw new Error('Unknown route mapping.');}
  else if(fingerprint!==expected)throw new Error('This route uses a different enemy dataset. Import cancelled to avoid selecting incorrect enemies.');
  const ids=values=>mapped?decodeMembers(permanent,deltas?memberDeltas(values,true):values):list(values).map(index=>itemAt(placements,index));
  if(!Array.isArray(pulls)||pulls.length>(extended?10000:500))throw invalid();
  const modifiers={};
  tuple(mods??[],3).forEach((row,i)=>{
    if(row==null)return;
    const [active,value,replaced]=tuple(row,i===0?2:3);
    if(i===0)modifiers.empowered={active:flag(active),enemies:ids(value)};
    else {
      const registered=value==null?null:mapped?itemAt(permanent.packs,value):null;
      modifiers[['empowered','ghorn','witch'][i]]={active:flag(active),packId:value==null?null:registered?.id??itemAt(packs,value),
        ...(replaced!=null?{replacedEnemies:ids(replaced)}:registered?{replacedEnemies:registered.members.map(i=>permanent.placements[i])}:{})};
    }
  });
  return {
    version:extended?3:2,dungeonId:dungeon.id,buildId,name,shadow:flag(shadow),modifiers,excluded:ids(excluded),priorityTargets:ids(priorityTargets),...(difficulty===undefined||(difficulty===null&&priorityTargets!==undefined)?{}:{difficulty}),
    pulls:pulls.map((row,i)=>{
      const [enemies,name,color,note,customName]=tuple(row,5);
      if(!Array.isArray(enemies))throw invalid();
      return {enemies:ids(enemies),name:name??`Pull ${i+1}`,color:readColor(color,pullColor(i)),note:note??'',customName:flag(customName)};
    }),
    ...(extended?{markers:list(markers).map(row=>{const [mapId,position,color,icon,label]=tuple(row,5);return {mapId,position,color:readColor(color,COLORS[0]),icon,label};})}:{}),
    drawings:list(drawings).map(row=>{
      const [mapId,kind,points,color,text,width,icon]=tuple(row,extended?7:6);
      return {mapId,kind:itemAt(['line','portal','invis','note'],kind),points,color:readColor(color,COLORS[0]),text:text??'',...(width==null?{}:{width}),...(icon==null?{}:{icon})};
    }),
  };
}

export async function decodeRoute(text,dungeons,enemies,loadDungeon){
  text=text.trim();
  if(!text)throw new Error('Paste a route string first.');
  if(text.length>27_000_000)throw tooLarge();
  if(text.startsWith('#route='))text=decodeURIComponent(text.slice(7));
  else if(!/^R[1234]\./.test(text)){
    let url;try{url=new URL(text);}catch{throw new Error('Paste a valid route string or Share link.');}
    if(!url.hash.startsWith('#route='))throw new Error('This link does not contain a route.');
    text=decodeURIComponent(url.hash.slice(7));
  }
  if(new TextEncoder().encode(text).length>LIMIT)throw tooLarge();
  if(!/^R[1234]\./.test(text))throw invalid();
  const encoded=text.slice(PREFIX.length);
  if(!/^[A-Za-z0-9_-]+$/.test(encoded))throw invalid();
  let bytes;
  try{bytes=Uint8Array.from(atob(encoded.replace(/-/g,'+').replace(/_/g,'/')),c=>c.charCodeAt(0));}
  catch{throw invalid();}
  const decoded=await transform(bytes,DecompressionStream);
  const payload=JSON.parse(new TextDecoder('utf-8',{fatal:true}).decode(decoded));
  if(!Array.isArray(payload))throw invalid();
  if(loadDungeon)await loadDungeon(`Level.ID.${payload[0]}`);
  const deltas=text.startsWith('R4.'),mapped=text.startsWith('R3.')||deltas;
  const value=await expandRoute(payload,dungeons,text.startsWith('R2.')||mapped&&payload.length>9,mapped,deltas);
  return validateRoute(value,dungeons,enemies);
}
