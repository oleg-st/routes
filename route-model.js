export function englishDefaultLabel(name){
  if(name==='\u041d\u043e\u0432\u044b\u0439 \u043c\u0430\u0440\u0448\u0440\u0443\u0442')return 'New route';
  if(name==='\u0418\u043c\u043f\u043e\u0440\u0442\u0438\u0440\u043e\u0432\u0430\u043d\u043d\u044b\u0439 \u043c\u0430\u0440\u0448\u0440\u0443\u0442')return 'Imported route';
  return typeof name==='string'?name.replace(/^\u041f\u0443\u043b\u043b (\d+)$/,'Pull $1'):name;
}
export function pullColor(index){
  if(index<COLORS.length)return COLORS[index];
  const h=(index*137.508)%360,s=.78,l=.6;
  const channel=n=>{const k=(n+h/30)%12,a=s*Math.min(l,1-l);return Math.round(255*(l-a*Math.max(-1,Math.min(k-3,9-k,1)))).toString(16).padStart(2,'0');};
  return '#'+channel(0)+channel(8)+channel(4);
}
