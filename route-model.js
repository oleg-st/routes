export function movePull(route,from,to){
  if(!Number.isInteger(from)||!Number.isInteger(to)||from<0||to<0||from>=route.pulls.length||to>=route.pulls.length||from===to)return;
  // Colors belong to list positions; names and encounter contents follow their pull.
  const colors=route.pulls.map(p=>p.color);
  route.pulls.splice(to,0,route.pulls.splice(from,1)[0]);
  route.pulls.forEach((pull,index)=>{
    if(!hasCustomPullName(pull))pull.name=`Pull ${index+1}`;
    pull.color=colors[index];
  });
}
