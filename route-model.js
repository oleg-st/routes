export function replacedIds(route,dungeon){
  const result=new Set();
  for(const kind of ['ghorn','witch']){const mod=route.modifiers?.[kind];if(!mod?.active)continue;for(const id of replacementMembers(dungeon,mod.packId,mod.replacedEnemies))result.add(id);}
  return result;
}
export function effectivePositions(route,dungeon){
  const hidden=replacedIds(route,dungeon),result=correctDungeon(dungeon).enemies.filter(p=>!hidden.has(p.placementId));
  for(const kind of ['ghorn','witch']){
    const mod=route.modifiers?.[kind];if(!mod?.active||!mod.packId)continue;
    const members=new Set(replacementMembers(dungeon,mod.packId,mod.replacedEnemies));
    const spawns=nativeModifierSpawns(dungeon.id,kind,members);
    if(spawns.length){
      for(const spawn of spawns)result.push({id:modifierId(kind),placementId:spawn.placementId,packId:spawn.placementId,modifier:kind,worldPosition:spawn.worldPosition,mapImageId:spawn.mapImageId,mapPosition:spawn.mapPosition});
      continue;
    }
    const pack=dungeon.enemies.filter(p=>members.has(p.placementId)),first=pack.find(p=>p.mapPosition);
    const mapped=pack.filter(p=>p.mapPosition&&p.mapImageId===first?.mapImageId);
    if(!pack.length)continue;
    const world=mapped.filter(p=>p.worldPosition);
    const worldPosition=world.length?Object.fromEntries(['x','y','z'].map(k=>[k,world.reduce((s,p)=>s+p.worldPosition[k],0)/world.length])):null;
    const preset=modifierPositions[dungeon.id]?.[kind];
    const native=preset&&preset.replacedEnemies.length===members.size&&preset.replacedEnemies.every(id=>members.has(id))?preset:null;
    result.push({id:modifierId(kind),placementId:modifierId(kind),packId:modifierId(kind),modifier:kind,worldPosition:native?.worldPosition??worldPosition,mapMembers:native?[]:mapped,mapImageId:native?.mapImageId??first?.mapImageId??null,mapPosition:native?.mapPosition??(mapped.length?{x:mapped.reduce((s,p)=>s+p.mapPosition.x,0)/mapped.length,y:mapped.reduce((s,p)=>s+p.mapPosition.y,0)/mapped.length}:null)});
  }
  return result;
}
export function placementScore(pos,enemy,route){
  if(!enemy?.isBoss&&route.excluded.includes(pos.placementId))return 0;
  if(pos.modifier)return enemyScore(modifierStats[pos.modifier]);
  return enemyScore(enemy,!enemy?.isBoss&&route.modifiers?.empowered?.active&&route.modifiers.empowered.enemies.includes(pos.placementId));
}
const replacementHealth=Object.fromEntries(Object.entries(modifierStats).map(([kind,stats])=>[kind,stats.baseHealth]));
export function dungeonPackEfficiencies(dungeon,enemies,route,{difficulty=route.difficulty??0}={}){
  const totals=new Map(),values=new Map(),baselinePacks=new Map();
  let totalHealth=0,totalBaseHealth=0,complete=true;
  // Normalize against the original dungeon, so changing one pack never changes
  // the numeric efficiency of untouched packs. Recalculate from dataset HP.
  for(const pos of correctDungeon(dungeon).enemies){
    const enemy=enemies.get(pos.id);
    if(enemy?.isBoss)continue;
    if(enemy?.dungeonScore===0&&enemy.baseHealth==null)continue;
    if(!Number.isFinite(enemy?.baseHealth)||enemy.baseHealth<=0){complete=false;continue;}
    totalHealth+=enemyHealth(enemy,{difficulty});
    totalBaseHealth+=enemy.baseHealth;
    const pack=baselinePacks.get(pos.packId)||{score:0,health:0};
    pack.score+=enemyScore(enemy);pack.health+=enemy.baseHealth;
    baselinePacks.set(pos.packId,pack);
  }
  // Include every floor and every pack, independently of pulls or map filters.
  for(const pos of effectivePositions(route,dungeon)){
    const enemy=enemies.get(pos.id);
    if(!pos.modifier&&enemy?.isBoss)continue;
    const score=placementScore(pos,enemy,route);
    const baseHealth=enemy?.baseHealth??replacementHealth[pos.modifier];
    // Zero-score scenery with no HP is not a combat target.
    if(score===0&&baseHealth==null)continue;
    if(!Number.isFinite(score)||score<0||!Number.isFinite(baseHealth)||baseHealth<=0){complete=false;continue;}
    const health=placementHealth(pos,enemy,route,{difficulty});
    if(!Number.isFinite(health)||health<=0){complete=false;continue;}
    const pack=totals.get(pos.packId)||{score:0,health:0};
    pack.score+=score;pack.health+=health;
    totals.set(pos.packId,pack);
  }
  // An incomplete HP total cannot produce a reliable dungeon-wide ratio.
  if(complete&&totalHealth>0&&Number.isFinite(dungeon.requiredScore)&&dungeon.requiredScore>0){
    for(const [id,pack] of totals){
      const value=(pack.score/dungeon.requiredScore)/(pack.health/totalHealth);
      if(Number.isFinite(value))values.set(id,value);
    }
  }
  // Fix the color scale to unmodified packs. Difficulty, affixes and Chicken
  // may change a pack's rating, but must not recolor untouched packs.
  const ratings=values.size?[...baselinePacks.values()].map(pack=>(pack.score/dungeon.requiredScore)/(pack.health/totalBaseHealth)):[];
  const range=ratings.length?{min:Math.min(...ratings),max:Math.max(...ratings)}:null;
  return {values,range,totalHealth};
}
export function packEfficiencyColor(value,range){
  if(!Number.isFinite(value)||!range)return '#0f172a';
  // Equally efficient packs share a neutral color, including single-pack maps.
  const position=range.max>range.min?Math.max(0,Math.min(1,(value-range.min)/(range.max-range.min)))*4:2;
  const stops=[[15,23,42],[220,38,38],[249,115,22],[250,204,21],[34,197,94]];
  const index=Math.min(Math.floor(position),3),fraction=position-index;
  return `rgb(${stops[index].map((channel,i)=>Math.round(channel+(stops[index+1][i]-channel)*fraction)).join(',')})`;
}
export function setReplacement(route,kind,packId,dungeon,enemies){
  if(!['ghorn','witch'].includes(kind))throw new Error('Invalid modifier.');
  if(!modifierAvailable(dungeon.id,kind))throw new Error('Modifier unavailable in this dungeon.');
  const pack=dungeon.enemies.filter(p=>p.packId===packId);
  if(!pack.length||pack.some(p=>enemies.get(p.id)?.isBoss))throw new Error('Choose a non-boss pack.');
  const other=kind==='ghorn'?'witch':'ghorn';
  if(route.modifiers[other].packId===packId)throw new Error('This pack already has a replacement.');
  route.modifiers[kind]={active:true,packId,replacedEnemies:pack.map(p=>p.placementId)};
  // A changed replacement is deliberately unassigned until selected on the map.
  const ids=new Set(modifierPlacementIds(dungeon.id,kind));
  for(const p of route.pulls)p.enemies=p.enemies.filter(id=>!ids.has(id));
  route.excluded=route.excluded.filter(id=>!ids.has(id));
  route.priorityTargets=(route.priorityTargets||[]).filter(id=>!ids.has(id));
}
export function shadowTimeline(route,dungeon,enemies){
  let cumulative=0,previous=0;
  return route.pulls.map(p=>{const s=scorePull(p,dungeon,enemies,route);cumulative+=s.orbScore;const total=orbCount(cumulative,dungeon),orbs=total-previous,spawns=Math.min(shadowTarget(dungeon)/shadowOrbsPerLord,Math.floor(total/shadowOrbsPerLord))-Math.min(shadowTarget(dungeon)/shadowOrbsPerLord,Math.floor(previous/shadowOrbsPerLord));previous=total;return {orbs,total,spawns};});
}
export function scorePull(pull,dungeon,enemies,route){
  const positions=new Map(effectivePositions(route,dungeon).map(e=>[e.placementId,e]));
  const inactive=new Set([...replacedIds(route,dungeon),...['ghorn','witch'].filter(k=>!route.modifiers?.[k]?.active).flatMap(k=>modifierPlacementIds(dungeon.id,k))]);
  const canonical=id=>id;
  const excluded=new Set(route.excluded.map(canonical));
  let score=0,orbScore=0,unknown=0,bosses=0,count=0;
  for(const id of new Set(pull.enemies.map(canonical))){
    if(inactive.has(id))continue;
    const pos=positions.get(id);if(!pos){unknown++;continue;}
    const enemy=enemies.get(pos.id);const value=!enemy?.isBoss&&excluded.has(id)?0:placementScore(pos,enemy,route);
    if(value===null)unknown++;else {score+=value;if(enemy?.shadowOrbEligible!==false)orbScore+=value;}
    if(enemy?.isBoss)bosses++;count++;
  }
  return {score,orbScore,unknown,bosses,count,percent:dungeon.requiredScore>0?score/dungeon.requiredScore*100:null};
}
